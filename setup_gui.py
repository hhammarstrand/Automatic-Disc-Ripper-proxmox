# ---------------------------------------------------------------------------
# Load/save helpers (inline to avoid importing adr.* which needs deps)
# ---------------------------------------------------------------------------

def _load_yaml(path: Path) -> dict:
    """Load a YAML file.  Uses PyYAML if available, otherwise basic parsing."""
    try:
        import yaml
        with open(path, "r", encoding="utf-8") as fh:
            return yaml.safe_load(fh) or {}
    except ImportError:
        # Minimal fallback — read key: value pairs (no nested structures)
        data: dict = {}
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                if ":" in line:
                    key, _, val = line.partition(":")
                    val = val.strip()
                    if val.lower() in ("true", "false"):
                        data[key.strip()] = val.lower() == "true"
                    elif val.isdigit():
                        data[key.strip()] = int(val)
                    else:
                        data[key.strip()] = val.strip("'\"")
        return data


def _save_yaml(path: Path, data: dict) -> None:
    """Save config to YAML."""
    try:
        import yaml
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            yaml.dump(data, fh, default_flow_style=False, allow_unicode=True)
    except ImportError:
        # Minimal fallback
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("# Automatic Disc Ripper for Windows configuration (generated by setup GUI)\n\n")
            for key, val in data.items():
                if isinstance(val, bool):
                    fh.write(f"{key}: {'true' if val else 'false'}\n")
                elif isinstance(val, list):
                    fh.write(f"{key}: []\n")
                elif isinstance(val, dict):
                    fh.write(f"{key}: {{}}\n")
                else:
                    fh.write(f"{key}: {val}\n")


def _discover_preset_files() -> list[str]:
    """Return names of .json preset files in presets/ directory."""
    if not PRESETS_DIR.is_dir():
        return []
    return sorted(f.name for f in PRESETS_DIR.glob("*.json"))


