def _check_exe(path_str: str, name: str) -> str | None:
    """Return warning string if exe is missing, else None."""
    if not path_str:
        return f"{name}: no path specified"
    if not Path(path_str).is_file():
        return f"{name}: file not found ({path_str})"
    return None


