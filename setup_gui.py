class SetupGUI:
    """Automatic Disc Ripper for Windows configuration GUI."""

    SECTION_COLORS = {
        "tools": "#2563eb",      # blue
        "dirs": "#059669",       # green
        "tmdb": "#d97706",       # amber
        "handbrake": "#7c3aed",  # violet
        "options": "#dc2626",    # red
        "web": "#0891b2",        # cyan
    }

    def __init__(self, root: tk.Tk):
        self.root = root
        self.root.title("Automatic Disc Ripper for Windows Setup")
        self.root.resizable(True, True)
        self.root.minsize(640, 500)

        # Try to set a reasonable starting size
        self.root.geometry("740x720")

        # Style
        style = ttk.Style()
        style.theme_use("clam" if "clam" in style.theme_names() else "default")

        # Load existing config or defaults
        self.config_data = dict(DEFAULTS)
        if CONFIG_PATH.exists():
            try:
                loaded = _load_yaml(CONFIG_PATH)
                self.config_data.update(loaded)
            except Exception:
                pass  # stick with defaults
        elif EXAMPLE_PATH.exists():
            try:
                loaded = _load_yaml(EXAMPLE_PATH)
                self.config_data.update(loaded)
            except Exception:
                pass

        # Variables dict
        self.vars: dict[str, tk.Variable] = {}

        self._build_ui()

    # ------------------------------------------------------------------ #
    # UI construction
    # ------------------------------------------------------------------ #

    def _build_ui(self):
        # Header
        header = ttk.Frame(self.root)
        header.pack(fill="x", padx=12, pady=(12, 4))
        ttk.Label(header, text="Automatic Disc Ripper for Windows Setup",
                  font=("Segoe UI", 16, "bold")).pack(side="left")
        status_text = "config\\adr.yaml found" if CONFIG_PATH.exists() else "no config found"
        ttk.Label(header, text=f"({status_text})",
                  font=("Segoe UI", 9)).pack(side="left", padx=(10, 0))

        # Scrollable content area
        container = ttk.Frame(self.root)
        container.pack(fill="both", expand=True, padx=12, pady=4)

        canvas = tk.Canvas(container, highlightthickness=0)
        scrollbar = ttk.Scrollbar(container, orient="vertical", command=canvas.yview)
        self.scroll_frame = ttk.Frame(canvas)

        self.scroll_frame.bind(
            "<Configure>",
            lambda e: canvas.configure(scrollregion=canvas.bbox("all"))
        )
        canvas.create_window((0, 0), window=self.scroll_frame, anchor="nw")
        canvas.configure(yscrollcommand=scrollbar.set)

        canvas.pack(side="left", fill="both", expand=True)
        scrollbar.pack(side="right", fill="y")

        # Mouse wheel scrolling
        def _on_mousewheel(event):
            canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
        canvas.bind_all("<MouseWheel>", _on_mousewheel)

        # --- Sections ---
        self._section_tools()
        self._section_directories()
        self._section_tmdb()
        self._section_handbrake()
        self._section_options()
        self._section_web()

        # --- Bottom buttons ---
        btn_frame = ttk.Frame(self.root)
        btn_frame.pack(fill="x", padx=12, pady=(4, 12))

        ttk.Button(btn_frame, text="Validate", command=self._validate).pack(side="left", padx=(0, 6))
        ttk.Button(btn_frame, text="Save config\\adr.yaml", command=self._save).pack(side="left", padx=(0, 6))
        ttk.Button(btn_frame, text="Cancel", command=self.root.destroy).pack(side="right")

    def _add_section(self, title: str, color: str = "#333") -> ttk.LabelFrame:
        """Add a labeled section frame."""
        frame = ttk.LabelFrame(self.scroll_frame, text=f"  {title}  ",
                               padding=(10, 6))
        frame.pack(fill="x", pady=(8, 0))
        return frame

    def _file_row(self, parent: ttk.Frame, label: str, key: str,
                  filetypes: list[tuple[str, str]] | None = None) -> None:
        """Add a row with label, entry, and file browse button."""
        row = ttk.Frame(parent)
        row.pack(fill="x", pady=2)
        ttk.Label(row, text=label, width=22, anchor="w").pack(side="left")
        var = tk.StringVar(value=str(self.config_data.get(key, "")))
        self.vars[key] = var
        entry = ttk.Entry(row, textvariable=var)
        entry.pack(side="left", fill="x", expand=True, padx=(0, 4))

        def browse():
            ft = filetypes or [("Executable", "*.exe"), ("All files", "*.*")]
            path = filedialog.askopenfilename(
                title=f"Select {label}",
                filetypes=ft,
                initialdir=str(Path(var.get()).parent) if var.get() and Path(var.get()).parent.exists() else None,
            )
            if path:
                var.set(path)

        ttk.Button(row, text="Browse...", width=12, command=browse).pack(side="right")

    def _dir_row(self, parent: ttk.Frame, label: str, key: str) -> None:
        """Add a row with label, entry, and directory browse button."""
        row = ttk.Frame(parent)
        row.pack(fill="x", pady=2)
        ttk.Label(row, text=label, width=22, anchor="w").pack(side="left")
        var = tk.StringVar(value=str(self.config_data.get(key, "")))
        self.vars[key] = var
        entry = ttk.Entry(row, textvariable=var)
        entry.pack(side="left", fill="x", expand=True, padx=(0, 4))

        def browse():
            initial = var.get() if var.get() and Path(var.get()).exists() else None
            path = filedialog.askdirectory(title=f"Select {label}", initialdir=initial)
            if path:
                var.set(path)

        ttk.Button(row, text="Browse...", width=12, command=browse).pack(side="right")

    def _entry_row(self, parent: ttk.Frame, label: str, key: str,
                   show: str = "", width: int | None = None) -> None:
        """Add a simple label + entry row."""
        row = ttk.Frame(parent)
        row.pack(fill="x", pady=2)
        ttk.Label(row, text=label, width=22, anchor="w").pack(side="left")
        var = tk.StringVar(value=str(self.config_data.get(key, "")))
        self.vars[key] = var
        entry = ttk.Entry(row, textvariable=var, show=show)
        if width:
            entry.configure(width=width)
            entry.pack(side="left", padx=(0, 4))
        else:
            entry.pack(side="left", fill="x", expand=True, padx=(0, 4))

    def _check_row(self, parent: ttk.Frame, label: str, key: str) -> None:
        """Add a checkbox row."""
        row = ttk.Frame(parent)
        row.pack(fill="x", pady=2)
        var = tk.BooleanVar(value=bool(self.config_data.get(key, False)))
        self.vars[key] = var
        ttk.Checkbutton(row, text=label, variable=var).pack(side="left")

    def _combo_row(self, parent: ttk.Frame, label: str, key: str,
                   values: list[str]) -> None:
        """Add a label + combobox row."""
        row = ttk.Frame(parent)
        row.pack(fill="x", pady=2)
        ttk.Label(row, text=label, width=22, anchor="w").pack(side="left")
        var = tk.StringVar(value=str(self.config_data.get(key, "")))
        self.vars[key] = var
        combo = ttk.Combobox(row, textvariable=var, values=values, state="normal")
        combo.pack(side="left", fill="x", expand=True, padx=(0, 4))

